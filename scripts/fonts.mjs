// Copies the bundled preset fonts (latin + latin-ext subsets) from the pinned
// @fontsource-variable devDependencies into fonts/, with their OFL notice.
// Deterministic: the same lockfile always produces the same bytes.
// `node scripts/fonts.mjs --check` verifies fonts/ and the @font-face rules in
// styles/tokens.css against the packages without writing anything.
import { readFile, writeFile, mkdir, readdir } from 'node:fs/promises';
import { createRequire } from 'node:module';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { root } from './catalogue.mjs';

const require = createRequire(import.meta.url);
// family: CSS family name; axis: which fontsource variable file to ship.
// Fraunces ships its optical-size axis, which its display headings rely on.
export const families = [
  { family: 'Inter', package: '@fontsource-variable/inter', stem: 'inter', axis: 'wght' },
  { family: 'Fraunces', package: '@fontsource-variable/fraunces', stem: 'fraunces', axis: 'opsz' },
  { family: 'Plus Jakarta Sans', package: '@fontsource-variable/plus-jakarta-sans', stem: 'plus-jakarta-sans', axis: 'wght' },
];
const subsets = ['latin', 'latin-ext'];

async function expected() {
  const files = new Map();
  const notices = [];
  let licence;
  const ranges = new Map();
  for (const font of families) {
    const directory = path.dirname(require.resolve(`${font.package}/package.json`));
    const manifest = JSON.parse(await readFile(path.join(directory, 'package.json'), 'utf8'));
    const css = await readFile(path.join(directory, `${font.axis}.css`), 'utf8');
    for (const subset of subsets) {
      const source = `${font.stem}-${subset}-${font.axis}-normal.woff2`;
      files.set(`${font.stem}-${subset}.woff2`, await readFile(path.join(directory, 'files', source)));
      const face = css.split('@font-face').find(block => block.includes(`/files/${source}`));
      ranges.set(`${font.stem}-${subset}.woff2`, face.match(/unicode-range:\s*([^;]+);/)[1].replace(/\s+/g, ''));
    }
    const text = await readFile(path.join(directory, 'LICENSE'), 'utf8');
    const body = text.slice(text.indexOf('-----'));
    if (!body.includes('SIL OPEN FONT LICENSE Version 1.1')) throw new Error(`${font.package}: expected the SIL Open Font License`);
    if (licence !== undefined && licence !== body) throw new Error(`${font.package}: licence text differs`);
    licence = body;
    notices.push(`- **${font.family}** (\`${font.stem}-latin.woff2\`, \`${font.stem}-latin-ext.woff2\`): ${text.match(/^Copyright .*?\)/)[0]}. SIL Open Font License 1.1. Source: \`${font.package}@${manifest.version}\` (${font.axis} variable axis${font.axis === 'wght' ? '' : ' with weight'}).`);
  }
  files.set('OFL.txt', Buffer.from(licence));
  files.set('NOTICE.md', Buffer.from(`# Bundled fonts

These fonts are bundled with the theme presets and served by the Portal host at
\`/_portal/fonts/<library-version>/<file>\`. Only the Latin and Latin Extended subsets are included.
The fonts are licensed under the SIL Open Font License, Version 1.1 (OFL.txt in
this folder); the component library's MIT license does not relicense them.

${notices.join('\n')}

Generated by \`pnpm run fonts\` from the pinned devDependencies. Do not edit by hand.
`));
  return { files, ranges };
}

export async function checkFonts() {
  const { files, ranges } = await expected();
  const folder = path.join(root, 'fonts');
  const actual = (await readdir(folder).catch(() => [])).sort();
  if (JSON.stringify(actual) !== JSON.stringify([...files.keys()].sort())) throw new Error('fonts/ inventory differs; run pnpm run fonts');
  for (const [name, content] of files) if (!(await readFile(path.join(folder, name))).equals(content)) throw new Error(`fonts/${name} is stale; run pnpm run fonts`);
  const tokens = await readFile(path.join(root, 'styles/tokens.css'), 'utf8');
  // Font URLs carry the library version, so an upgrade changes every URL and the
  // host may serve them as immutable.
  const { version } = JSON.parse(await readFile(path.join(root, 'package.json'), 'utf8'));
  const faces = [...tokens.matchAll(/@font-face\s*\{([^}]*)\}/g)].map(m => m[1]);
  for (const body of faces) for (const [, url] of body.matchAll(/url\("([^"]+)"\)/g))
    if (!url.startsWith(`/_portal/fonts/${version}/`)) throw new Error(`styles/tokens.css: ${url} must be versioned as /_portal/fonts/${version}/<file>`);
  for (const [name, range] of ranges) {
    const face = faces.find(body => body.includes(`/_portal/fonts/${version}/${name}"`));
    if (!face || face.match(/unicode-range:\s*([^;]+);/)?.[1].replace(/\s+/g, '') !== range) throw new Error(`styles/tokens.css @font-face for ${name} must use the package unicode-range`);
  }
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  if (process.argv.includes('--check')) {
    await checkFonts();
    console.log('Bundled fonts and @font-face rules match the pinned packages.');
  } else {
    const { files } = await expected();
    await mkdir(path.join(root, 'fonts'), { recursive: true });
    for (const [name, content] of files) await writeFile(path.join(root, 'fonts', name), content);
    console.log(`Copied ${files.size - 2} font files with their OFL notice into fonts/.`);
  }
}
