import { readFile, writeFile, readdir } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
export const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
export const read = relative => readFile(path.join(root, relative), 'utf8');
const escapeCell = value => String(value).replaceAll('|', '\\|').replaceAll('\n', ' ');
export async function loadCatalogue() {
  const catalogue = JSON.parse(await read('catalogue.json'));
  if (catalogue.contractVersion !== 1 || !Array.isArray(catalogue.components)) throw new Error('Unsupported catalogue');
  const names = new Set();
  for (const item of catalogue.components) {
    if (!/^[a-z][a-z0-9-]*$/.test(item.name) || names.has(item.name)) throw new Error(`Invalid/duplicate name: ${item.name}`);
    names.add(item.name);
    for (const key of ['source', 'contract', 'example', 'rendered']) {
      const expected = `${key === 'source' || key === 'contract' ? 'components' : key === 'example' ? 'examples' : 'rendered'}/${item.name}.${key === 'contract' ? 'json' : 'html'}`;
      if (item[key] !== expected) throw new Error(`Unexpected ${key} path for ${item.name}`);
    }
    item.definition = JSON.parse(await read(item.contract));
    item.usage = await read(item.example);
    item.template = await read(item.source);
    if (!item.usage.includes('xmlns:t="urn:cococo:dataxml"')) throw new Error(`Missing canonical namespace: ${item.name}`);
    if (!item.definition.props || !item.definition.slots) throw new Error(`Missing contract fields: ${item.name}`);
    for (const [prop, config] of Object.entries(item.definition.props)) {
      if (!['string','boolean','integer','number','array','object','any'].includes(config.type)) throw new Error(`Invalid prop type ${item.name}.${prop}`);
      if (config.required && Object.hasOwn(config, 'default')) throw new Error(`Required prop has default: ${item.name}.${prop}`);
      if (config.enum && Object.hasOwn(config,'default') && !config.enum.includes(config.default)) throw new Error(`Default outside enum: ${item.name}.${prop}`);
    }
  }
  const files = await readdir(path.join(root, 'components'));
  const expected = [...names].flatMap(n => [`${n}.html`, `${n}.json`]).sort();
  if (JSON.stringify(files.sort()) !== JSON.stringify(expected)) throw new Error('Component directory and catalogue disagree');
  return catalogue;
}
export async function generatedDocuments() {
  const catalogue = await loadCatalogue();
  const sections = catalogue.components.map(c => {
    const props = Object.entries(c.definition.props).map(([name,p]) => `| \`${name}\` | ${p.type}${p.nullable ? ' or null' : ''} | ${p.required ? 'required' : Object.hasOwn(p,'default') ? `\`${escapeCell(JSON.stringify(p.default))}\`` : 'omitted'} | ${p.enum ? p.enum.map(v=>`\`${escapeCell(v)}\``).join(', ') : '—'} |`).join('\n');
    const slots = Object.entries(c.definition.slots).map(([name,s]) => `- \`${name}\`: ${s.required?'required':'optional'}`).join('\n') || 'None.';
    return `## ${c.name}\n\n${c.description}\n\nSource: [template](../${c.source}) · [contract](../${c.contract})\n\n${props ? '| Prop | Type | Default | Allowed values |\n| --- | --- | --- | --- |\n'+props : 'No props.'}\n\nSlots:\n\n${slots}\n\n### Usage\n\n\`\`\`xml\n${c.usage.trim()}\n\`\`\`\n\n### Accessibility and limits\n\n${c.accessibility}\n`;
  });
  const tokensCSS = await read('styles/tokens.css');
  const defaultBlock = tokensCSS.slice(tokensCSS.indexOf('.portal-theme {'),tokensCSS.indexOf('.portal-theme[data-theme='));
  const tokens = [...defaultBlock.matchAll(/(--portal-[a-z0-9-]+):\s*([^;]+);/g)].map(([,name,value])=>({name,default:value}));
  const componentDocs = `# Component reference\n\nGenerated from catalogue.json, component contracts and executable example source. Do not edit this file directly. Library ${catalogue.version}, contract ${catalogue.contractVersion}.\n\n${sections.join('\n')}\n`;
  const tokenDocs = '# Token reference\n\nGenerated from styles/tokens.css. Override on the theme root or a component wrapper.\n\n| Token | Light default |\n| --- | --- |\n'+tokens.map(t=>`| \`${t.name}\` | \`${t.default}\` |`).join('\n')+'\n';
  const generated = {...catalogue, tokens};
  const instructions = await read('LLM.md');
  const authoring = await read('docs/authoring.md');
  const themes = await read('docs/themes.md');
  return new Map([
    ['docs/components.md', componentDocs],
    ['docs/tokens.md', tokenDocs],
    ['catalogue.generated.json', JSON.stringify(generated,null,2)+'\n'],
    ['llms.txt', '# Portal Components\n\n> Ownable DataXML presentation components; Lua remains page/server-side.\n\n- [Authoring instructions](LLM.md)\n- [Complete LLM reference](llms-full.txt)\n- [Machine-readable catalogue](catalogue.generated.json)\n- [Authoring](docs/authoring.md)\n- [Components](docs/components.md)\n- [Theme tokens](docs/tokens.md)\n'],
    ['llms-full.txt', [instructions,authoring,themes,tokenDocs,componentDocs].join('\n\n')]
  ].map(([file, content]) => [file, content.trimEnd() + '\n']));
}
if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const check = process.argv.includes('--check');
  for (const [file, content] of await generatedDocuments()) {
    if (check) {
      if (await read(file).catch(()=>null) !== content) throw new Error(`Stale generated file ${file}; run npm run docs`);
    } else await writeFile(path.join(root,file),content);
  }
  console.log(check ? 'Catalogue and generated documentation are current.' : 'Generated component, token and LLM references.');
}
