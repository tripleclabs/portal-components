// Generates styles/icons.css (one mask rule per icon named in the icon
// prop's enum in components/icon.portal) and icons/NOTICE.md (the Lucide ISC
// and Feather MIT notices) from the pinned lucide-static devDependency.
// Deterministic: the same lockfile produces the same bytes.
// `node scripts/icons.mjs --check` verifies both files without writing them.
import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { createRequire } from 'node:module';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { root, read, readComponent } from './catalogue.mjs';

const require = createRequire(import.meta.url);
const wrap = (words, width = 76) => words.reduce((lines, word) => {
  const last = lines.at(-1);
  if (last && last.length + word.length + 1 <= width) lines[lines.length - 1] = `${last} ${word}`; else lines.push(word);
  return lines;
}, []).join('\n * ');
// Icons that point along the inline axis; they mirror on right-to-left pages.
const directional = ['arrow-left', 'arrow-right', 'arrow-up-right', 'chevron-left', 'chevron-right', 'external-link', 'log-out'];

const number = /^[\s,]*([-+]?(?:\d+\.?\d*|\.\d+)(?:[eE][-+]?\d+)?)/;
// Path data that can follow another path's data unchanged. A path's first
// moveto is absolute even when written `m`, and its extra coordinate pairs are
// implicit linetos (relative after `m`), so `m12 19-7-7` becomes `M12 19l-7-7`.
export function standalonePathData(d) {
  d = d.trim();
  if (!d.startsWith('m')) return d;
  let rest = d.slice(1);
  const coordinates = [];
  for (let i = 0; i < 2; i++) {
    const match = rest.match(number);
    if (!match) throw new Error(`Unexpected path data: ${d}`);
    coordinates.push(match[1]);
    rest = rest.slice(match[0].length);
  }
  const implicit = number.test(rest);
  return `M${coordinates[0]} ${coordinates[1]}${implicit ? 'l' : ''}${implicit ? rest.replace(/^[\s,]*/, '') : rest}`;
}

// Shape-only SVG for a CSS mask, which reads alpha only: no class or size
// attributes, a short opaque stroke colour, and sibling paths merged into one
// (the strokes share every attribute, so the union is identical). Characters
// that are unsafe in a CSS url() or in host-serialized <style> text are
// percent-encoded.
export function maskURL(svg) {
  const body = svg.replace(/<!--[\s\S]*?-->/g, '').match(/<svg[^>]*>([\s\S]*)<\/svg>/)[1]
    .replace(/\s*\n\s*/g, '').replace(/\s*\/>/g, '/>').replaceAll('"', "'");
  if (/[&\\]/.test(body)) throw new Error('Unexpected character in icon source');
  const paths = [...body.matchAll(/<path d='([^']*)'\/>/g)].map(match => match[1]);
  const others = body.replace(/<path d='[^']*'\/>/g, '');
  const merged = (paths.length ? `<path d='${paths.map((d, i) => i ? standalonePathData(d) : d).join('')}'/>` : '') + others;
  const markup = `<svg xmlns='http://www.w3.org/2000/svg' viewBox='0 0 24 24' fill='none' stroke='red' stroke-width='2' stroke-linecap='round' stroke-linejoin='round'>${merged}</svg>`;
  return `url("data:image/svg+xml,${markup.replaceAll('<', '%3C').replaceAll('>', '%3E')}")`;
}

export async function iconStylesheet() {
  const names = (await readComponent('icon')).definition.props.name.enum;
  const directory = path.dirname(require.resolve('lucide-static/package.json'));
  const { version, license } = JSON.parse(await readFile(path.join(directory, 'package.json'), 'utf8'));
  if (license !== 'ISC') throw new Error(`lucide-static: expected the ISC licence, found ${license}`);
  const licence = await readFile(path.join(directory, 'LICENSE'), 'utf8');
  const isc = licence.slice(0, licence.indexOf('---')).trim();
  const featherList = licence.match(/derived from the Feather project:\s*\n\s*\n([^\n]+)/)[1].split(', ');
  const fromFeather = names.filter(name => featherList.includes(name));
  const mit = licence.slice(licence.indexOf('The MIT License')).trim();
  const rules = [];
  for (const name of names) {
    const svg = await readFile(path.join(directory, 'icons', `${name}.svg`), 'utf8');
    rules.push(`.portal-icon[data-icon="${name}"] { --_icon: ${maskURL(svg)}; }`);
  }
  const mirrored = directional.filter(name => names.includes(name)).map(name => `[data-icon="${name}"]`).join(', ');
  // The /*! comment survives the host's minified bundle.
  const css = `/*! Icons: Lucide (lucide-static@${version}), ISC licence; some derive from Feather, MIT. Notices: icons/NOTICE.md */
/* Generated by \`pnpm run icons\` from the icon contract's enum. Do not edit.
 * The .portal-icon base rule lives in components/icon.portal. */
${rules.join('\n')}
.portal-icon:is(${mirrored}):dir(rtl) { transform: scaleX(-1); }
`;
  const notice = `# Bundled icons

\`styles/icons.css\` embeds ${names.length} icons from [Lucide](https://lucide.dev)
(\`lucide-static@${version}\`) as CSS masks. The component library's MIT
license does not relicense them. They are used under the following notices.

## Lucide (ISC)

\`\`\`text
${isc}
\`\`\`

## Feather (MIT)

${wrap(`These bundled icons derive from Feather: ${fromFeather.join(', ')}.`.split(' '), 80).replaceAll('\n * ', '\n')}

\`\`\`text
${mit}
\`\`\`

Generated by \`pnpm run icons\` from the pinned devDependency. Do not edit by hand.
`;
  return { css, notice };
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const { css, notice } = await iconStylesheet();
  if (process.argv.includes('--check')) {
    if (await read('styles/icons.css').catch(() => null) !== css) throw new Error('styles/icons.css is stale; run pnpm run icons');
    if (await read('icons/NOTICE.md').catch(() => null) !== notice) throw new Error('icons/NOTICE.md is stale; run pnpm run icons');
    console.log('Icon stylesheet and notice match the icon contract and the pinned Lucide package.');
  } else {
    await writeFile(path.join(root, 'styles/icons.css'), css);
    await mkdir(path.join(root, 'icons'), { recursive: true });
    await writeFile(path.join(root, 'icons/NOTICE.md'), notice);
    console.log(`Generated ${(await readComponent('icon')).definition.props.name.enum.length} icon rules in styles/icons.css and icons/NOTICE.md.`);
  }
}
